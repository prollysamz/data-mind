-- Optional isolated governance demo. Requires Enterprise edition (dynamic masking)
-- and an administrator. This script is NOT run by the agent or normal bootstrap.
-- Uses only a fictional contact; never attaches a policy to user data.
-- Read-only credentials cannot execute this setup. Run in Snowsight as an admin.
USE ROLE ACCOUNTADMIN;
CREATE SCHEMA IF NOT EXISTS DATAMIND.GOVERNANCE_DEMO;
CREATE TABLE IF NOT EXISTS DATAMIND.GOVERNANCE_DEMO.CONTACTS (
  CONTACT_ID INTEGER, EMAIL VARCHAR
);
MERGE INTO DATAMIND.GOVERNANCE_DEMO.CONTACTS target
USING (SELECT 1 AS CONTACT_ID, 'demo@example.invalid' AS EMAIL) source
ON target.CONTACT_ID = source.CONTACT_ID
WHEN NOT MATCHED THEN INSERT (CONTACT_ID, EMAIL) VALUES (source.CONTACT_ID, source.EMAIL);

CREATE MASKING POLICY IF NOT EXISTS DATAMIND.GOVERNANCE_DEMO.MASK_EMAIL
AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN CURRENT_ROLE() = 'ACCOUNTADMIN' THEN val ELSE '[MASKED]' END;
ALTER TABLE DATAMIND.GOVERNANCE_DEMO.CONTACTS
  MODIFY COLUMN EMAIL SET MASKING POLICY DATAMIND.GOVERNANCE_DEMO.MASK_EMAIL;
GRANT USAGE ON SCHEMA DATAMIND.GOVERNANCE_DEMO TO ROLE DATAMIND_READONLY;
GRANT SELECT ON TABLE DATAMIND.GOVERNANCE_DEMO.CONTACTS TO ROLE DATAMIND_READONLY;

-- Compare actual database-enforced results; secondary roles must remain disabled.
ALTER SESSION SET QUERY_TAG = 'datamind:governance-demo';
USE SECONDARY ROLES NONE;
SELECT CONTACT_ID, EMAIL FROM DATAMIND.GOVERNANCE_DEMO.CONTACTS; -- fictional email
USE ROLE DATAMIND_READONLY;
SELECT CONTACT_ID, EMAIL FROM DATAMIND.GOVERNANCE_DEMO.CONTACTS; -- [MASKED]
