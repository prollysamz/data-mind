"""Write the exact installed versions of datamind[dev,snowflake] and its dependency closure."""
import platform, sys
from importlib import metadata
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

seen, order = {}, []
def walk(name, extras=()):
    key = canonicalize_name(name)
    try:
        dist = metadata.distribution(name)
    except metadata.PackageNotFoundError:
        return
    if key not in seen:
        seen[key] = dist.version; order.append(key)
    for raw in dist.requires or []:
        req = Requirement(raw)
        env = {"extra": ""}
        ok = req.marker is None or req.marker.evaluate(env) or any(req.marker.evaluate({"extra": e}) for e in extras)
        if ok and canonicalize_name(req.name) not in seen:
            walk(req.name)
walk("datamind", ("dev", "snowflake"))
seen.pop("datamind", None)
print("# Exact versions DataMind's tests and evaluations ran with (datamind[dev] closure).")
print(f"# Python {platform.python_version()} on {platform.system()} {platform.release()}; generated by scripts/write_lockfile.py")
print("# Install: pip install -r requirements.lock && pip install -e . --no-deps")
for k in sorted(seen):
    print(f"{k}=={seen[k]}")
